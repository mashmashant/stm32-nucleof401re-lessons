#include <stdint.h>

/* ============================================================
 * RCC
 * ============================================================ */

#define RCC_AHB1ENR    (*(volatile uint32_t *)0x40023830U)
#define RCC_APB1ENR    (*(volatile uint32_t *)0x40023840U)
#define RCC_APB2ENR    (*(volatile uint32_t *)0x40023844U)

/* ============================================================
 * GPIOA
 * ============================================================ */

#define GPIOA_MODER    (*(volatile uint32_t *)0x40020000U)
#define GPIOA_AFRL     (*(volatile uint32_t *)0x40020020U)

/* ============================================================
 * USART2
 * ============================================================ */

#define USART2_SR      (*(volatile uint32_t *)0x40004400U)
#define USART2_DR      (*(volatile uint32_t *)0x40004404U)
#define USART2_BRR     (*(volatile uint32_t *)0x40004408U)
#define USART2_CR1     (*(volatile uint32_t *)0x4000440CU)

/* ============================================================
 * ADC1
 * ============================================================ */

#define ADC1_SR        (*(volatile uint32_t *)0x40012000U)
#define ADC1_CR1       (*(volatile uint32_t *)0x40012004U)
#define ADC1_CR2       (*(volatile uint32_t *)0x40012008U)
#define ADC1_SMPR1     (*(volatile uint32_t *)0x4001200CU)
#define ADC1_SQR1      (*(volatile uint32_t *)0x4001202CU)
#define ADC1_SQR3      (*(volatile uint32_t *)0x40012034U)
#define ADC1_DR        (*(volatile uint32_t *)0x4001204CU)

/* Спільний регістр ADC */
#define ADC_CCR        (*(volatile uint32_t *)0x40012304U)

/* ============================================================
 * Біти регістрів
 * ============================================================ */

#define USART_SR_TXE       (1U << 7)
#define USART_CR1_TE       (1U << 3)
#define USART_CR1_UE       (1U << 13)

#define ADC_SR_EOC         (1U << 1)
#define ADC_CR2_ADON       (1U << 0)
#define ADC_CR2_SWSTART    (1U << 30)
#define ADC_CCR_TSVREFE    (1U << 23)

/* ============================================================
 * Програмна затримка
 * ============================================================ */

static void delay(volatile uint32_t count)
{
    while (count > 0U)
    {
        count--;
        __asm volatile ("nop");
    }
}

/* ============================================================
 * Передавання одного символу
 * ============================================================ */

static void uart_send_char(char character)
{
    while ((USART2_SR & USART_SR_TXE) == 0U)
    {
    }

    USART2_DR = (uint32_t)character;
}

/* ============================================================
 * Передавання рядка
 * ============================================================ */

static void uart_send_string(const char *text)
{
    while (*text != '\0')
    {
        uart_send_char(*text);
        text++;
    }
}

/* ============================================================
 * Передавання беззнакового числа
 * ============================================================ */

static void uart_send_uint32(uint32_t number)
{
    char buffer[10];
    uint32_t index = 0U;

    if (number == 0U)
    {
        uart_send_char('0');
        return;
    }

    while (number > 0U)
    {
        buffer[index] = (char)('0' + (number % 10U));
        number /= 10U;
        index++;
    }

    while (index > 0U)
    {
        index--;
        uart_send_char(buffer[index]);
    }
}

/* ============================================================
 * Передавання знакового числа
 * ============================================================ */

static void uart_send_int32(int32_t number)
{
    if (number < 0)
    {
        uart_send_char('-');
        number = -number;
    }

    uart_send_uint32((uint32_t)number);
}

/* ============================================================
 * Одне перетворення ADC1
 * ============================================================ */

static uint32_t adc1_read(void)
{
    /* Запуск програмного перетворення */
    ADC1_CR2 |= ADC_CR2_SWSTART;

    /* Очікування завершення перетворення */
    while ((ADC1_SR & ADC_SR_EOC) == 0U)
    {
    }

    /*
     * Читання DR повертає результат
     * та очищає прапорець EOC.
     */
    return ADC1_DR;
}

/* ============================================================
 * Головна функція
 * ============================================================ */

int main(void)
{
    uint32_t adc_value;
    uint32_t sensor_voltage_mv;
    int32_t temperature_c;

    /* --------------------------------------------------------
     * 1. Тактування GPIOA, USART2 та ADC1
     * -------------------------------------------------------- */

    RCC_AHB1ENR |= (1U << 0);
    RCC_APB1ENR |= (1U << 17);
    RCC_APB2ENR |= (1U << 8);

    /* --------------------------------------------------------
     * 2. PA2 — USART2_TX, альтернативна функція AF7
     * -------------------------------------------------------- */

    GPIOA_MODER &= ~(3U << 4);
    GPIOA_MODER |=  (2U << 4);

    GPIOA_AFRL &= ~(0xFU << 8);
    GPIOA_AFRL |=  (7U << 8);

    /* --------------------------------------------------------
     * 3. USART2: 115200 бод, передавач увімкнений
     * -------------------------------------------------------- */

    USART2_BRR = 0x008BU;
    USART2_CR1 |= USART_CR1_TE;
    USART2_CR1 |= USART_CR1_UE;

    /* --------------------------------------------------------
     * 4. Частота ADC = PCLK2 / 4
     *
     * ADCPRE = 01 у бітах 17:16
     * -------------------------------------------------------- */

    ADC_CCR &= ~(3U << 16);
    ADC_CCR |=  (1U << 16);

    /* --------------------------------------------------------
     * 5. Увімкнення внутрішнього температурного сенсора
     * -------------------------------------------------------- */

    ADC_CCR |= ADC_CCR_TSVREFE;

    /*
     * Після ввімкнення сенсору потрібен час
     * для стабілізації.
     */
    delay(10000U);

    /* --------------------------------------------------------
     * 6. Один канал у регулярній послідовності
     *
     * L = 0000 означає одне перетворення.
     * -------------------------------------------------------- */

    ADC1_SQR1 &= ~(0xFU << 20);

    /* --------------------------------------------------------
     * 7. Перший канал послідовності — канал 18
     * -------------------------------------------------------- */

    ADC1_SQR3 &= ~0x1FU;
    ADC1_SQR3 |= 18U;

    /* --------------------------------------------------------
     * 8. Максимальний час вибірки для каналу 18
     *
     * SMP18 = 111: 480 циклів ADC.
     * -------------------------------------------------------- */

    ADC1_SMPR1 &= ~(7U << 24);
    ADC1_SMPR1 |=  (7U << 24);

    /* CR1 залишаємо без спеціальних режимів */
    ADC1_CR1 = 0U;

    /* --------------------------------------------------------
     * 9. Увімкнення ADC1
     * -------------------------------------------------------- */

    ADC1_CR2 |= ADC_CR2_ADON;

    delay(10000U);

    uart_send_string(
        "\r\n"
        "STM32F401RE internal temperature sensor\r\n"
        "ADC1 channel 18\r\n\r\n"
    );

    /* --------------------------------------------------------
     * 10. Головний цикл вимірювань
     * -------------------------------------------------------- */

    while (1)
    {
        adc_value = adc1_read();

        /*
         * Перетворення коду ADC у мілівольти:
         *
         * U = ADC × 3300 / 4095.
         *
         * Припускаємо, що VDDA = 3,3 В.
         */
        sensor_voltage_mv =
            (adc_value * 3300U) / 4095U;

        /*
         * Приблизна температура:
         *
         * T = 25 + (760 мВ - U) / 2,5 мВ/°C.
         *
         * Ділення на 2,5 реалізовано як ×10 / 25.
         */
        temperature_c =
            25 + (((int32_t)760 -
                   (int32_t)sensor_voltage_mv) * 10) / 25;

        uart_send_string("ADC = ");
        uart_send_uint32(adc_value);

        uart_send_string(" | Voltage = ");
        uart_send_uint32(sensor_voltage_mv);
        uart_send_string(" mV");

        uart_send_string(" | Temperature ~ ");
        uart_send_int32(temperature_c);
        uart_send_string(" C\r\n");

        delay(4000000U);
    }
}
